// หาคอร์สที่เกี่ยวกับข้อความนี้มากที่สุด 1 ตัว (ไม่ยัดหลายอัน — รกและดูขายของ)
export function suggestCourse(...texts) {
  const hay = texts.filter(Boolean).join(" ").toLowerCase();
  if (!hay.trim()) return null;
  let best = null, bestScore = 0;
  for (const r of RULES) {
    let score = 0;
    for (const k of r.kw) if (hay.includes(k)) score += k.length;   // คำยาว = เฉพาะเจาะจงกว่า ให้น้ำหนักมากกว่า
    if (score > bestScore) { bestScore = score; best = r; }
  }
  return best;
}
