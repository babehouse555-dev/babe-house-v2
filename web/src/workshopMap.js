// คอร์สนี้มีคลาสสดที่สอนเรื่องเดียวกันไหม
export function workshopForCourse(courseId) {
  return PAIRS[String(courseId ?? "")] || null;
}

// ควรชวนไปคลาสสดไหม — ชวนเฉพาะคน "ซื้อแล้วแต่ยังเรียนไม่จบ" (< 60%)
// คนเรียนจบแล้วไม่ต้องเห็น เพราะเขาทำเองได้แล้ว การชวนจะกลายเป็นการยัดขาย
export function shouldSuggestWorkshop(courseId, progressPct) {
  if (!workshopForCourse(courseId)) return false;
  const p = Number(progressPct);
  return !Number.isFinite(p) || p < 60;
}
